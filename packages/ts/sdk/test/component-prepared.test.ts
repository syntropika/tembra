import { expect, test } from "bun:test";
import { BrowserExecution } from "../src/interpreter/browser.ts";
import {
  preparedComponent,
  preparedRegistry,
  PREPARED_FORMAT,
  PREPARED_GENERATOR,
  type PreparedComponentSource,
} from "../src/interpreter/component/prepared.ts";

const DIGEST = "a".repeat(64);

function source(overrides: Partial<PreparedComponentSource> = {}): PreparedComponentSource {
  return {
    format: PREPARED_FORMAT,
    generator: PREPARED_GENERATOR,
    orb: { name: "calc", apiVersion: 1 },
    artifact: DIGEST,
    maximumPages: 65536,
    imports: [],
    suspending: [],
    promising: [],
    cores: [{ name: "orb.core.wasm", pages: 1, load: () => new ArrayBuffer(0) }],
    instantiate: async () => ({}),
    ...overrides,
  };
}

/** A verifier stub: every artifact claims to be compiled; digests decide acceptance. */
function contracts(digest: string) {
  let freed = 0;
  return {
    freed: () => freed,
    module: {
      default: async () => {},
      compiledArtifact: () => true,
      WasmArtifact: class {
        constructor() {
          throw new Error("Raw compiled artifacts must never reach the source constructor");
        }
      } as never,
      WasmPreparedComponent: class {
        constructor(_bytes: Uint8Array, digests: string[]) {
          if (!digests.includes(digest))
            throw "no prepared browser adapter is registered for this compiled Orb artifact";
        }
        digest() {
          return digest;
        }
        description() {
          return JSON.stringify({ name: "calc", apiVersion: 1, kind: "component" });
        }
        contributions() {
          return "{}";
        }
        bind(): number {
          throw new Error("No methods expected");
        }
        validate(): string {
          throw new Error("No values expected");
        }
        request(): string {
          throw new Error("No queries expected");
        }
        free() {
          freed++;
        }
      },
    },
  };
}

test("the generated-module helper checks its description and brands the result", () => {
  const component = preparedComponent(source());
  expect(component).toEqual({ orb: { name: "calc", apiVersion: 1 }, artifact: DIGEST });
  expect(Object.isFrozen(component)).toBe(true);
  expect(preparedRegistry([component]).get(DIGEST)?.orb.name).toBe("calc");
  // Copies and hand-written look-alikes are never trusted as prepared adapters.
  expect(() => preparedRegistry([{ ...component }])).toThrow("generated by Tembra tooling");
  expect(() => preparedComponent(source({ generator: "other" }))).toThrow("expected");
  expect(() => preparedComponent(source({ artifact: "A".repeat(64) }))).toThrow("digest");
  expect(() => preparedComponent(source({ maximumPages: 65537 }))).toThrow("maximum pages");
  expect(() =>
    preparedComponent(source({ cores: [{ name: "evil.wasm", load: () => new ArrayBuffer(0) }] })),
  ).toThrow("unexpected core module");
  expect(() =>
    preparedComponent(
      source({
        cores: [
          { name: "orb.conditional-suspending-1-i32-to-i32.wasm", load: () => new Uint8Array() },
        ],
      }),
    ),
  ).toThrow("no component core module");
  for (const name of [
    "orb.conditional-host-import-0.wasm",
    "orb.conditional-suspending-1-i32-to-i32.wasm",
    "orb.conditional-suspending-2-i32-to-i32.wasm",
    "orb.conditional-suspending-3-i32-to-i32.wasm",
    "orb.conditional-suspending-3-i32-to-void.wasm",
  ])
    expect(() =>
      preparedComponent(
        source({ cores: [...source().cores, { name, load: () => new Uint8Array() }] }),
      ),
    ).not.toThrow();
  expect(() =>
    preparedComponent(
      source({
        cores: [
          ...source().cores,
          { name: "orb.conditional-suspending-9-i32-to-void.wasm", load: () => new Uint8Array() },
        ],
      }),
    ),
  ).toThrow("unexpected core module");
  expect(() => preparedComponent(source({ imports: ["a", "a"] }))).toThrow("duplicate");
  // Two different adapters may not claim the same artifact.
  expect(() => preparedRegistry([component, preparedComponent(source())])).toThrow(
    "Two prepared components",
  );
  expect(preparedRegistry([component, component]).size).toBe(1);
});

test("a compiled Orb without a registered adapter fails with build instructions", async () => {
  const contract = contracts(DIGEST);
  const backend = new BrowserExecution({}, contract.module);
  await expect(backend.materialize({ artifact: new Uint8Array([1]) })).rejects.toThrow(
    "browser: true",
  );
  expect(contract.freed()).toBe(0);
});

test("a compiled Orb whose bytes match no registered digest is refused", async () => {
  const contract = contracts("b".repeat(64));
  const backend = new BrowserExecution(
    { components: [preparedComponent(source())] },
    contract.module,
  );
  await expect(backend.materialize({ artifact: new Uint8Array([1]) })).rejects.toThrow(
    "matches no registered prepared adapter",
  );
  expect(contract.freed()).toBe(0);
});

test("a matched compiled Orb frees its verifier handle once when installation fails", async () => {
  const contract = contracts(DIGEST);
  const backend = new BrowserExecution(
    // A wrong identity fails before any instance exists, with or without JSPI.
    { components: [preparedComponent(source({ orb: { name: "other", apiVersion: 1 } }))] },
    contract.module,
  );
  await expect(backend.materialize({ artifact: new Uint8Array([1]) })).rejects.toThrow();
  expect(contract.freed()).toBe(1);
});
